import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';

// Use Vite's existing JSON/module resolution, exactly as the app does.
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const { getMonogramCoverageInventory } = await server.ssrLoadModule('/src/utils/monogramSupport.js');
  const rows = getMonogramCoverageInventory();
  const counts = {};
  for (const row of rows) counts[row.status] = (counts[row.status] || 0) + 1;
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ counts, rows }, null, 2));
  } else {
    console.log(`${rows.length} monograms: ${JSON.stringify(counts)}`);
    if (process.argv.includes('--write')) {
      const escape = text => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
      const report = [
        '# Monogram calculation wiring inventory', '',
        'Generated by `npm run audit:monograms -- --write` from the committed selectors and reviewed numeric grants. Game-table refreshes remain manual.', '',
        'This is a wiring audit, not a percentage of complete in-game support. A dependency path can be conditional, display-only, or use a provisional formula. Empty proc/utility entries may be outside the on-hit model.', '',
        'Counts: ' + Object.entries(counts).map(([status, count]) => `${status}: **${count}**`).join('; ') + '.', '',
        '| Monogram ID | Selector slots | Wiring | Targets | Known limitation |',
        '|---|---|---|---|---|',
        ...rows.map(row => `| ${escape(row.id)} | ${row.slots.join(', ') || 'Imported grants'} | ${row.label} | ${row.targets.join(', ') || '—'} | ${escape(row.note)} |`), '',
      ].join('\n');
      await writeFile('docs/monogram-coverage.md', report);
      console.log('Wrote docs/monogram-coverage.md');
    }
  }
} finally {
  await server.close();
}
